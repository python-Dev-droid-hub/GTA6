/**
 * Cut curated plates from official trailers for homepage cinema sections.
 * Fan/dev use only — do not ship as if affiliated with Rockstar.
 *
 * node scripts/extract-trailer-chunks.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const downloads = path.join(process.env.USERPROFILE || "", "Downloads");

const sources = {
  t1: path.join(downloads, "Grand Theft Auto VI Trailer 1_1080p.mp4"),
  t2: path.join(downloads, "Grand Theft Auto VI Trailer 2_1080p.mp4"),
};

const outDir = path.join(root, "public", "videos", "cinema");
const postersDir = path.join(root, "public", "images", "cinema");

/** @type {{ id: string; src: keyof typeof sources; start: number; dur: number; label: string }[]} */
const chunks = [
  // Trailer 2 — primary cinematic plates
  { id: "hero-scrub", src: "t2", start: 8, dur: 5.5, label: "Hero scroll scrub" },
  { id: "coast-loop", src: "t2", start: 28, dur: 6, label: "Coast full-bleed loop" },
  { id: "neon-loop", src: "t2", start: 72, dur: 6, label: "Neon night loop" },
  { id: "heat-loop", src: "t2", start: 110, dur: 5.5, label: "Heat / motion loop" },
  // Trailer 1 — supporting / media cards
  { id: "vice-pulse", src: "t1", start: 12, dur: 5, label: "Vice pulse" },
  { id: "chase-cut", src: "t1", start: 48, dur: 5, label: "Chase cut" },
  { id: "trailer1-teaser", src: "t1", start: 0, dur: 12, label: "Trailer 1 teaser plate" },
  { id: "trailer2-teaser", src: "t2", start: 0, dur: 12, label: "Trailer 2 teaser plate" },
];

function cut(input, start, dur, output) {
  execFileSync(
    "ffmpeg",
    [
      "-y",
      "-ss",
      String(start),
      "-i",
      input,
      "-t",
      String(dur),
      "-c:v",
      "libx264",
      "-preset",
      "fast",
      "-crf",
      "23",
      "-pix_fmt",
      "yuv420p",
      "-an",
      "-movflags",
      "+faststart",
      output,
    ],
    { stdio: "inherit" },
  );
}

function poster(input, output) {
  execFileSync(
    "ffmpeg",
    [
      "-y",
      "-ss",
      "0.2",
      "-i",
      input,
      "-frames:v",
      "1",
      "-q:v",
      "3",
      output,
    ],
    { stdio: "inherit" },
  );
}

for (const key of Object.keys(sources)) {
  if (!fs.existsSync(sources[key])) {
    console.error("Missing", sources[key]);
    process.exit(1);
  }
}

fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(postersDir, { recursive: true });

const manifest = [];

for (const c of chunks) {
  const mp4 = path.join(outDir, `${c.id}.mp4`);
  const jpg = path.join(postersDir, `${c.id}.jpg`);
  console.log(`\n→ ${c.id} (${c.label})`);
  cut(sources[c.src], c.start, c.dur, mp4);
  poster(mp4, jpg);
  manifest.push({
    id: c.id,
    label: c.label,
    videoSrc: `/videos/cinema/${c.id}.mp4`,
    posterSrc: `/images/cinema/${c.id}.jpg`,
    duration: c.dur,
    source: c.src,
  });
}

const ts = `/**
 * Auto-generated by scripts/extract-trailer-chunks.mjs
 * Fan/dev media plates — not affiliated with Rockstar.
 */
export type CinemaClip = {
  id: string;
  label: string;
  videoSrc: string;
  posterSrc: string;
  duration: number;
  source: "t1" | "t2";
};

export const cinemaClips = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly CinemaClip[];

export const cinemaById = Object.fromEntries(
  cinemaClips.map((c) => [c.id, c]),
) as Record<string, CinemaClip>;
`;

fs.writeFileSync(path.join(root, "src", "data", "cinema-clips.ts"), ts, "utf8");
console.log("\nManifest → src/data/cinema-clips.ts");
