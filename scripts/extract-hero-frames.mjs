/**
 * Extracts a WebP frame sequence for ScrollScrubVideo.
 *
 * Usage: npm run extract:hero-frames
 * Requires ffmpeg on PATH.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const input = path.join(root, "public", "videos", "hero.mp4");
const outDir = path.join(root, "public", "videos", "hero-frames");
const manifest = path.join(root, "src", "data", "hero-scrub-frames.ts");

const FPS = 60; // short clips need denser sampling across a long scroll runway
const WIDTH = 1280;

if (!fs.existsSync(input)) {
  console.error("Missing", input);
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) {
  if (/\.(webp|jpg|jpeg|png)$/i.test(f)) fs.unlinkSync(path.join(outDir, f));
}

console.log("Extracting frames…");
execFileSync(
  "ffmpeg",
  [
    "-y",
    "-i",
    input,
    "-vf",
    `fps=${FPS},scale=${WIDTH}:-1:flags=lanczos`,
    "-c:v",
    "libwebp",
    "-quality",
    "72",
    path.join(outDir, "frame_%04d.webp"),
  ],
  { stdio: "inherit" },
);

const files = fs
  .readdirSync(outDir)
  .filter((f) => f.endsWith(".webp"))
  .sort();

if (files.length < 2) {
  console.error("Expected multiple frames, got", files.length);
  process.exit(1);
}

const urls = files.map((f) => `/videos/hero-frames/${f}`);
const source = `/**
 * Auto-generated by scripts/extract-hero-frames.mjs — do not edit by hand.
 * Frames: ${files.length} @ ${FPS}fps, width ${WIDTH}
 */
export const heroScrubFrames = ${JSON.stringify(urls, null, 2)} as const;

export const heroScrubMeta = {
  count: ${files.length},
  fps: ${FPS},
  width: ${WIDTH},
} as const;
`;

fs.writeFileSync(manifest, source, "utf8");
console.log(`Wrote ${files.length} frames → ${outDir}`);
console.log(`Manifest → ${manifest}`);
