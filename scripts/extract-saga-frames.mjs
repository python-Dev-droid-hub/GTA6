/**
 * Extract WebP sequences for cinema saga chapters (coast, neon, heat).
 * node scripts/extract-saga-frames.mjs
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const cinema = path.join(root, "public", "videos", "cinema");
const outRoot = path.join(root, "public", "videos", "saga-frames");

const chapters = [
  { id: "coast", file: "coast-loop.mp4", fps: 20 },
  { id: "neon", file: "neon-loop.mp4", fps: 20 },
  { id: "heat", file: "heat-loop.mp4", fps: 20 },
];

const WIDTH = 1280;
const VER = "saga1";
const manifests = [];

fs.mkdirSync(outRoot, { recursive: true });

for (const ch of chapters) {
  const input = path.join(cinema, ch.file);
  if (!fs.existsSync(input)) {
    console.error("Missing", input);
    process.exit(1);
  }
  const dir = path.join(outRoot, ch.id);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });

  console.log(`\n→ ${ch.id}`);
  execFileSync(
    "ffmpeg",
    [
      "-y",
      "-i",
      input,
      "-vf",
      `fps=${ch.fps},scale=${WIDTH}:-1:flags=lanczos`,
      "-c:v",
      "libwebp",
      "-quality",
      "70",
      path.join(dir, "frame_%04d.webp"),
    ],
    { stdio: "inherit" },
  );

  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".webp"))
    .sort();
  const urls = files.map(
    (f) => `/videos/saga-frames/${ch.id}/${f}?v=${VER}`,
  );
  manifests.push({ id: ch.id, count: files.length, urls });
}

const ts = `/**
 * Auto-generated by scripts/extract-saga-frames.mjs
 */
${manifests
  .map(
    (m) => `export const sagaFrames${m.id[0].toUpperCase()}${m.id.slice(1)} = ${JSON.stringify(m.urls, null, 2)} as const;
`,
  )
  .join("\n")}
export const sagaFrameMeta = ${JSON.stringify(
  Object.fromEntries(manifests.map((m) => [m.id, { count: m.count }])),
  null,
  2,
)} as const;
`;

fs.writeFileSync(path.join(root, "src", "data", "saga-frames.ts"), ts, "utf8");
console.log("Wrote src/data/saga-frames.ts");
